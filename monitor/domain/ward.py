"""
領域層 — 床號 → 單位（病房）推導
====================================
看板要能「只顯示某幾個單位的呼吸器」，管理頁要能看出「這台在哪個單位」，
兩邊都需要把床號換算成單位。這是一條業務規則，因此放領域層由伺服器算好後
隨 snapshot／device_meta 廣播，不讓看板與管理頁各寫一份
（CLAUDE.md §5：前端不得包含業務規則）。

床號有兩種格式，對應院內兩種病房編碼方式：

**加護／特殊單位** —— 病房代碼直接寫在床號開頭：

    MI01 CCU03 SI12 NI35 PI19 RCC21 IR01 BR21 BC02 HP13-1
    → 取開頭的連續英文字母

⚠️ **刻意不寫死代碼清單。** 院方 `get_inPatient_wardList()` 列的 33 個單位
**不完整**——燒傷加護（`BC`）就不在表上，但實際設備資料裡有（BC02，
一台 EvitaV300）。寫死成 `^(MI|CCU|SI|NI|PI|RCC|IR|BR|HP)` 的話，`BC02`
會完全比對不到、該台機器在看板篩選時直接消失，而且不會有任何錯誤訊息。
取字母前綴則是漏列或新增的單位都自動就對。

**一般病房** —— `{樓層2碼}{房間2碼}-{床位}`，樓層碼與病房代碼有固定換算：

    3520-1 → 樓層 35 → N15        （N 系列：樓層碼 = 病房號 + 20）
    0711-1 → 樓層 07 → R07        （R 系列：樓層碼 = 病房號）
    8811-1 → 樓層 88 → M08        （M/MP 系列：樓層碼 = 病房號 + 80）
    8611   → 樓層 86 → MP06       （身心科一房一床，沒有床位序號）

**已知限制：G 院區（NSH9／NSH10／NSR11）推不出來。**
判斷 G 院區必須看 Zone 欄位，而院方設備系統 `getDeviceList` 的回傳裡沒有
這個欄位。兩個具體衝突：
- `NSR11` 的床號是 `A01-1`，會被字母前綴規則判成單位「A」
- `NSH10` 的 `1001-2` 與 `R10` 的 `1011-1` 都以樓層碼 `10` 開頭，無從區分
實測的呼吸器清冊裡沒有任何一台在 G 院區（呼吸器都在本院），因此暫不處理；
日後若 G 院區也要納管，需要另一個帶 Zone 的資料來源，不是改這裡的規則。
"""

import re

# 認得出樓層碼、但不在下表的一般病房床號歸成這類。
# 必須有這個退路：呼吸器有時會在一般病房使用，歸不了類的話那些機器會因為
# 篩選不到而整台從看板消失——寧可粗一點，也不能讓機器不見。
GENERAL_WARD = "一般病房"


def _floor_map() -> dict:
    """樓層碼 → 病房代碼。三個系列各有各的換算，用產生的方式寫出來，
    規則本身就看得見（也比逐條列出少一種打錯的機會）。"""
    table = {}
    for n in range(8, 18):                      # N08–N17 → 樓層 28–37
        table[f"{n + 20:02d}"] = f"N{n:02d}"
    for n in (7, 9, 10, 11, 12, 13, 14):        # R07、R09–R14 → 樓層同號（無 R08）
        table[f"{n:02d}"] = f"R{n:02d}"
    for n in (6, 7):                            # MP06–MP07 → 樓層 86–87
        table[f"{n + 80:02d}"] = f"MP{n:02d}"
    for n in (8, 9):                            # M08–M09 → 樓層 88–89
        table[f"{n + 80:02d}"] = f"M{n:02d}"
    return table


FLOOR_TO_WARD = _floor_map()

_LETTER_PREFIX = re.compile(r"^([A-Za-z]+)")
# 一般病房：4 位數房號（前 2 碼是樓層），床位序號選填（身心科一房一床）
_ROOM_NUMBER = re.compile(r"^(\d{2})\d{2}(?:-\d+)?$")


def from_bed(bed) -> str:
    """床號 → 單位代碼；認不得或沒有床號一律回空字串（未指定）。

    回空字串而不是猜一個值：床號來自院方系統，格式不在我們掌握中，
    寧可顯示「未指定」讓人看得出來，也不要編一個看起來像真的的單位。
    """
    bed = str(bed or "").strip()
    if not bed:
        return ""

    match = _LETTER_PREFIX.match(bed)
    if match:
        return match.group(1).upper()

    match = _ROOM_NUMBER.match(bed)
    if match:
        # 樓層碼不在表上 → 仍歸一般病房，別讓機器從篩選中消失
        return FLOOR_TO_WARD.get(match.group(1), GENERAL_WARD)

    return ""
